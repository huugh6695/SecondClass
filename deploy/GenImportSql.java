import org.mindrot.jbcrypt.BCrypt;

import java.io.BufferedReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Turn a "student-id,name,role" roster into ready-to-run INSERT statements.
 *
 * WHY THIS TOOL EXISTS
 *   The system has no sign-up endpoint and no "create user" endpoint: accounts are
 *   provisioned up front. The convention is that a new account's initial password is the
 *   last 6 digits of the student id (that is exactly what the admin "reset password"
 *   feature produces). But the password column stores a bcrypt hash, and bcrypt is
 *   salted -- every student id yields a different hash, and SQL cannot compute bcrypt.
 *   So the hashes have to be produced by code, which is what this program does.
 *
 * HOW TO RUN
 *   Use gen-import-sql.bat (it knows where the jbcrypt jar lives). Example:
 *     gen-import-sql.bat users.csv
 *
 * SOURCE ENCODING NOTE
 *   This file is deliberately pure ASCII. Java 17 runs a single .java file using the
 *   PLATFORM default charset to read it, which is GBK on a Chinese Windows box -- any
 *   non-ASCII literal here would be mis-decoded. All user-facing text is in the
 *   companion README (UTF-8) instead.
 *
 * OUTPUT ENCODING NOTE
 *   The generated .sql is written with an explicit UTF-8 writer (NOT stdout), so real
 *   names with Chinese characters survive. Do not change this to System.out: the console
 *   encoding would leak into the file and MySQL would store mojibake.
 */
public class GenImportSql {

    /** Output file name used when the caller does not give one. */
    private static final String DEFAULT_OUT = "import-users.sql";

    public static void main(String[] args) throws Exception {
        if (args.length < 1 || "-h".equals(args[0]) || "--help".equals(args[0])) {
            usage();
            return;
        }

        Path csv = Paths.get(args[0]);
        if (!Files.isReadable(csv)) {
            System.err.println("ERROR: cannot read roster file: " + csv.toAbsolutePath());
            System.err.println("       (quote the path if it contains spaces)");
            System.exit(2);
        }
        Path out = Paths.get(args.length >= 2 ? args[1] : DEFAULT_OUT);

        List<String[]> rows = new ArrayList<>();      // {id, name, role, plainPassword}
        List<String> problems = new ArrayList<>();
        int lineNo = 0;

        try (BufferedReader r = Files.newBufferedReader(csv, StandardCharsets.UTF_8)) {
            String line;
            while ((line = r.readLine()) != null) {
                lineNo++;
                // Excel "Save as CSV" often prepends a UTF-8 BOM; it would silently become
                // part of the first student id and the login would fail forever.
                if (lineNo == 1) {
                    line = line.replace("\uFEFF", "");
                }
                String s = line.trim();
                if (s.isEmpty() || s.startsWith("#")) {
                    continue;
                }
                String[] c = s.split("\\s*,\\s*");
                if (c.length < 3) {
                    problems.add("line " + lineNo + ": expected 3 columns (id,name,role), got " + c.length);
                    continue;
                }
                String id = c[0];
                String name = c[1];
                String role = normalizeRole(c[2]);
                if (role == null) {
                    problems.add("line " + lineNo + ": unknown role '" + c[2]
                            + "' (use STUDENT/STAFF/ADMIN)");
                    continue;
                }
                if (id.isEmpty() || name.isEmpty()) {
                    problems.add("line " + lineNo + ": id or name is empty");
                    continue;
                }
                String pwd = (c.length >= 4 && !c[3].isEmpty())
                        ? c[3]
                        : (id.length() >= 6 ? id.substring(id.length() - 6) : id);
                rows.add(new String[]{id, name, role, pwd});
            }
        }

        // All-or-nothing: never emit a half-imported roster.
        if (!problems.isEmpty()) {
            System.err.println("ERROR: the roster has problems, nothing was generated:");
            for (String p : problems) {
                System.err.println("  - " + p);
            }
            System.exit(3);
        }
        if (rows.isEmpty()) {
            System.err.println("ERROR: no usable rows in " + csv.toAbsolutePath());
            System.exit(3);
        }

        StringBuilder sb = new StringBuilder();
        sb.append("-- Generated by deploy/GenImportSql.java from roster: ").append(csv.getFileName()).append('\n');
        sb.append("-- Accounts: ").append(rows.size())
          .append("   Initial password = last 6 digits of the id (override with column 4).\n");
        sb.append("-- NOTE: run ONCE against an empty database. Re-running fails on the primary\n");
        sb.append("--       key on purpose, so it cannot silently revert a password somebody changed.\n");
        sb.append("SET NAMES utf8mb4;\n\n");
        for (String[] row : rows) {
            // salt rounds 10 == what AuthService.changePassword uses, so hashes are interchangeable
            String hash = BCrypt.hashpw(row[3], BCrypt.gensalt(10));
            sb.append("INSERT INTO t_user (user_id, user_name, user_type, password, status) VALUES ('")
              .append(esc(row[0])).append("', '")
              .append(esc(row[1])).append("', '")
              .append(row[2]).append("', '")
              .append(hash).append("', 'ACTIVE');\n");
        }
        sb.append("\n-- SELF-CHECK: SELECT user_id, user_name, user_type, status FROM t_user ORDER BY user_id;\n");

        // Explicit UTF-8: this is the whole point of not using stdout.
        Files.writeString(out, sb.toString(), StandardCharsets.UTF_8);

        Map<String, Integer> byRole = new LinkedHashMap<>();
        for (String[] row : rows) {
            byRole.merge(row[2], 1, Integer::sum);
        }
        System.out.println("OK: " + rows.size() + " account(s) written to " + out.toAbsolutePath());
        for (Map.Entry<String, Integer> e : byRole.entrySet()) {
            System.out.println("    " + e.getKey() + " x " + e.getValue());
        }
        System.out.println("    initial passwords (id -> password):");
        for (String[] row : rows) {
            System.out.println("      " + row[0] + "  " + row[3]);
        }
        System.out.println();
        System.out.println("Next: import it into the database, e.g.");
        System.out.println("  mysql -uroot -p --default-character-set=utf8mb4 second_classroom < " + out);
    }

    /** Accepts the English enum names or their Chinese equivalents (kept as escapes: see file header). */
    private static String normalizeRole(String raw) {
        String v = raw.trim();
        if (v.equalsIgnoreCase("STUDENT") || v.equals("\u5b66\u751f")) {
            return "STUDENT";                 // xue sheng
        }
        if (v.equalsIgnoreCase("STAFF") || v.equals("\u5e72\u4e8b")) {
            return "STAFF";                   // gan shi
        }
        if (v.equalsIgnoreCase("ADMIN") || v.equals("\u7ba1\u7406\u5458")) {
            return "ADMIN";                   // guan li yuan
        }
        return null;
    }

    /** Single-quote escaping so a stray apostrophe in a name cannot break the statement. */
    private static String esc(String v) {
        return v.replace("'", "''");
    }

    private static void usage() {
        System.out.println("Turn a roster into INSERT statements (bcrypt-hashed passwords).");
        System.out.println();
        System.out.println("Usage: gen-import-sql.bat <roster.csv> [output.sql]");
        System.out.println("       (output defaults to " + DEFAULT_OUT + ")");
        System.out.println();
        System.out.println("Roster format: UTF-8 text, one account per line, comma separated.");
        System.out.println("Lines starting with # are comments.");
        System.out.println();
        System.out.println("    id,name,role[,initial-password]");
        System.out.println("    2023001001,Alice,STUDENT");
        System.out.println("    2023002001,Bob,STAFF");
        System.out.println("    2023003001,Carol,ADMIN,Secret123");
        System.out.println();
        System.out.println("role accepts STUDENT/STAFF/ADMIN (Chinese words also work).");
        System.out.println("Leave column 4 empty and the initial password becomes the LAST 6 DIGITS");
        System.out.println("of the id -- which is exactly what the admin 'reset password' produces.");
    }
}
